defmodule LocalFileProofVectors do
  def trace_loop(rows) do
    receive do
      {:trace,_,:call,{m,f,args}}->trace_loop([{m,f,length(args)}|rows])
      {:get,p}->send(p,{:calls,Enum.reverse(rows)});trace_loop(rows)
    end
  end
  def invoke(fun,tracer) do
    task=Task.async(fn->
      :erlang.trace(self(),true,[:call,:set_on_spawn,{:tracer,tracer}])
      try do {:ok,fun.()}
      rescue _->{:error,:exception}
      catch {:recovery,code,reason}->{:recovery,code,reason};{:domain,code}->{:domain,code}
      after :erlang.trace(self(),false,[:all]) end
    end)
    Task.await(task,30000)
  end
  def fingerprint(p) do
    case File.lstat(p) do
      {:error,:enoent}->:absent
      {:ok,s}->{ADHD.RecoveryFiles.identity(s),if(s.type==:regular,do: ADHD.RecoveryFiles.sha(File.read!(p)),else: s.type)}
    end
  end
  def snapshot(s) do
    b=ADHD.Storage.bytes(s);<<"ADHDSTATE",1,(:crypto.hash(:sha256,b))::binary,b::binary>>
  end
  def reject(id,paths,fun,tracer,expected \\ nil) do
    before=Enum.map(paths,&fingerprint/1);result=invoke(fun,tracer)
    rejected=case {expected,result} do
      {nil,{:recovery,_,_}}->true;{nil,{:domain,_}}->true
      {{code,reason},{:recovery,code,reason}}->true
      _->false
    end
    %{"id"=>id,"passed"=>rejected and before==Enum.map(paths,&fingerprint/1),"result"=>if(match?({:ok,_},result),do: "accepted",else: inspect(result)),"inputs_unchanged"=>before==Enum.map(paths,&fingerprint/1)}
  end
end
